"""Small helpers to write OpenFOAM v1912 dictionaries and run utilities."""
from __future__ import annotations

import os
import subprocess
from pathlib import Path

FOAM_ENV = dict(FOAM_ETC='/usr/share/openfoam/etc', WM_PROJECT_DIR='/usr/share/openfoam',
                WM_PROJECT_VERSION='v1912', WM_PROJECT='OpenFOAM')

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  OA2IS-WheelMotor-CFD - generated by oa2is_cfd (OpenFOAM v1912)
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    location    "{loc}";
    object      {obj};
}}
"""


def write(case: Path, rel: str, body: str, cls: str = 'dictionary'):
    p = Path(case) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(HEADER.format(cls=cls, loc=str(Path(rel).parent), obj=Path(rel).name) + body.strip() + '\n')
    return p


def vec(v):
    return '(' + ' '.join(f'{float(x):.10g}' for x in v) + ')'


PATCHED_LIBS = '/opt/oa2is-openfoam-patches/lib'   # tools/build_patched_openfoam.sh


def env():
    e = dict(os.environ)
    e.update(FOAM_ENV)
    if os.path.isdir(PATCHED_LIBS):
        e['LD_LIBRARY_PATH'] = PATCHED_LIBS + ':' + e.get('LD_LIBRARY_PATH', '')
    return e


def run(case: Path, *cmd, log: str | None = None, check: bool = True, timeout=None):
    """Run an OpenFOAM utility in `case`, logging to case/log.<name>."""
    case = Path(case)
    name = log or cmd[0]
    with open(case / f'log.{name}', 'w') as f:
        r = subprocess.run(list(cmd), cwd=case, env=env(), stdout=f, stderr=subprocess.STDOUT, timeout=timeout)
    if check and r.returncode != 0:
        tail = (case / f'log.{name}').read_text(errors='replace').splitlines()[-25:]
        raise RuntimeError(f'{" ".join(cmd)} failed in {case}:\n' + '\n'.join(tail))
    return r.returncode
