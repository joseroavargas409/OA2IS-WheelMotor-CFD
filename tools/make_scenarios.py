#!/usr/bin/env python3
"""Generate the scenario YAML files with KINEMATICALLY CONSISTENT inputs.

The truck speed v(t) is the single input of a moving scenario. From it:
  wheel  omega_w = v / r_tire
  motor  rpm     = omega_w * i_total * 60 / (2 pi)      (i_total = 32.6087, model)
  vehicle accel  a_fwd = dv/dt                         (apparent body force -a)
so the rotor speed change and the inertial load are the SAME event and are not
counted twice. The first `SPINUP` seconds ramp the gear train from rest to the
initial speed WITHOUT a vehicle acceleration: this is a numerical start-up of
the flow field from the quiescent state (excluded from statistics), not a
physical launch of the truck.

Assumptions (documented in docs/ESCENARIOS.md):
  scenarios 01-05: r_tire = 1.95 m (53/80R63 class tyre, loaded radius ~1.9-2.0 m)
  i_total = 32.6087 (two planetary stages of the model: 1/(0.2*0.15335))
  scenarios 06-09 ("ciclo real"): speed -> motor rpm with the MEASURED ratio
  48.43 motor rpm per km/h (median of a 930E-5 operating record, aggregate
  statistic only; equivalent to a 1.79 m rolling radius with i = 32.6),
  grades/speeds/decelerations = medians of that record, air density at the
  site altitude (81 kPa, 60 C), oil level set by the hub-cover level plugs.
usage: python3 tools/make_scenarios.py [out_dir]
"""
import math
import sys
from pathlib import Path

import yaml

R_TIRE = 1.95
I_TOTAL = 32.6087
SPINUP = 0.05
OUT = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / 'scenarios')

COMMON = dict(write_interval=0.01, side='right', oil_litres=95.0, oil_rho=900.0, oil_temperature_c=60.0,
              oil_nu=2.64238e-4, air_rho=1.06, air_nu=1.9e-5, sigma=0.030, mesh='ib_coarse')


RPM_PER_KMH = 48.43          # measured motor rpm per km/h (930E-5 record, median; p10 45.7, p90 50.4)
_RPM = {'model': lambda v: v / 3.6 / R_TIRE * I_TOTAL * 60 / (2 * math.pi),
        'measured': lambda v: RPM_PER_KMH * v}
_mode = ['model']


def rpm_of(v_kmh):
    return _RPM[_mode[0]](v_kmh)


def speed_profile(phases, v0_kmh, t_end):
    """phases: [(t_start, t_stop, a_fwd m/s2)] after spin-up. Returns
    motor_rpm table and accel table (piecewise constant a, linear v)."""
    knots = sorted({SPINUP, t_end, *[p[0] for p in phases], *[p[1] for p in phases]})
    def a_at(t):
        for t0, t1, a in phases:
            if t0 <= t < t1:
                return a
        return 0.0
    v = v0_kmh / 3.6
    rpm = [[0.0, 0.0], [SPINUP, round(rpm_of(v0_kmh), 3)]]
    acc = [[0.0, 0.0, 0.0]]
    for t0, t1 in zip(knots[:-1], knots[1:]):
        a = a_at(0.5 * (t0 + t1))
        acc += [[round(t0, 6), a, 0.0], [round(t1 - 1e-6, 6), a, 0.0]]
        v += a * (t1 - t0)
        rpm.append([round(t1, 6), round(rpm_of(v * 3.6), 3)])
    rpm.append([100.0, rpm[-1][1]])
    acc.append([100.0, 0.0, 0.0])
    return rpm, acc


def main():
    sensors = yaml.safe_load((OUT / '_sensors.yaml').read_text())
    v_nom = 20.0                                   # km/h, loaded haul road
    sc = []
    sc.append(dict(name='01_reposo', duration=0.25, motor_rpm=[[0, 0], [100, 0]], mechanisms='stopped',
                   description='Reposo: mecanismos detenidos, aceite 95 L a 60 C bajo gravedad. Referencia del '
                               'nivel estatico y caso de comparacion "detenido".'))
    rpm, acc = speed_profile([], v_nom, 0.25)
    sc.append(dict(name='02_operacion_normal', duration=0.25, motor_rpm=rpm,
                   description=f'Operacion nominal: camion a {v_nom:.0f} km/h constante (motor {rpm_of(v_nom):.0f} rpm, '
                               f'rueda {rpm_of(v_nom) / I_TOTAL:.1f} rpm); arranque numerico 0-{SPINUP} s.'))
    sc.append(dict(name='03_operacion_inclinada', duration=0.25, motor_rpm=rpm, pitch_deg=round(math.degrees(math.atan(0.10)), 3),
                   roll_deg=4.0,
                   description=f'Subida con pendiente 10 % (5.71 deg) y peralte lateral 4 deg a {v_nom:.0f} km/h.'))
    rpm4, acc4 = speed_profile([(0.08, 0.15, 1.5), (0.15, 0.40, -3.0)], v_nom, 0.40)
    sc.append(dict(name='04_transitorio', duration=0.40, motor_rpm=rpm4, accel=acc4,
                   description=f'Transitorio: {v_nom:.0f} km/h, aceleracion +1.5 m/s2 (0.08-0.15 s) y frenado '
                               '-3.0 m/s2 (0.15-0.40 s); rpm del motor coherente con v(t).'))
    sc.append(dict(name='05_bajo_inventario', duration=0.25, motor_rpm=rpm, oil_litres=55.0,
                   description=f'Bajo inventario: 55 L (fuga simulada) a {v_nom:.0f} km/h.'))
    for s in sc:
        s.setdefault('sensors', sensors)
    sc += real_cycle()
    for s in sc:
        d = dict(COMMON)
        d.update(s)
        body = '# OA2IS-WheelMotor-CFD scenario, generated by tools/make_scenarios.py (do not edit by hand)\n'
        (OUT / f"{s['name']}.yaml").write_text(body + yaml.safe_dump(d, sort_keys=False, allow_unicode=True))
        print(s['name'], 'rpm', d['motor_rpm'][:4], '...')


# ---------------------------------------------------------------- real cycle
# Hub-cover magnetic plugs (Komatsu wheel motor guide): 8 plugs on one circle of
# the hub cover; the oil level is checked at rest with two plugs on a horizontal
# line, oil must reach them (max 90 L in the guide for GDY108C). Radius 0.270 m
# measured from the guide photographs (plug circle = 0.479 x cover bolt circle,
# bolt circle ~0.565 m); level pair at 240 and 300 deg -> level y = -0.234 m.
PLUG_R, PLUG_Z = 0.270, -1.7195           # 15 mm inside the hub-cover inner face (z = -1.7345)
PLUG_ANGLES = [30, 60, 120, 150, 210, 240, 300, 330]
LEVEL_Y = round(PLUG_R * math.sin(math.radians(240)), 4)   # -0.2338 m
AIR_RHO_SITE = 0.844                      # 81 kPa (11.7 psi measured), 60 C


def plug_sensors():
    plugs = []
    for k, a in enumerate(PLUG_ANGLES, 1):
        role = 'tapon de nivel' if a in (240, 300) else 'tapon magnetico'
        plugs.append(dict(id=f'P{k}', angle_deg=a, name=f'Tapa de maza, {role} a {a} deg (en reposo)'))
    return [dict(group='hub_cover_plugs', part='out', radius=PLUG_R, z=PLUG_Z, n_ring=120,
                 electrode_axis='z', plugs=plugs,
                 description='Sensores en los puertos de los tapones magneticos de la tapa de maza; giran con la maza')]


def real_cycle():
    _mode[0] = 'measured'
    fixed = yaml.safe_load((OUT / '_sensors.yaml').read_text()) + yaml.safe_load((OUT / '_sensors_v41.yaml').read_text())
    base = dict(air_rho=AIR_RHO_SITE, oil_level_y_flat=LEVEL_Y, mesh='ib_test', sensors=fixed,
                rotating_sensors=plug_sensors(), capacitive_stencil=True)
    note = ('Velocidad/pendiente/aceleracion: medianas de un registro real de operacion de un 930E-5 '
            '(solo estadisticas agregadas); rpm motor = 48.43 x km/h (medido). Aceite al nivel de los tapones '
            'de la tapa de maza; aire a 81 kPa.')
    out = []
    out.append(dict(base, name='06_real_reposo_nivel', duration=0.15, motor_rpm=[[0, 0], [100, 0]], mechanisms='stopped',
                    description='Camion detenido en terreno plano: control de nivel por los tapones (aceite justo en '
                                'los tapones de 240/300 deg). ' + note))
    v = 14.07; rpm, _ = speed_profile([], v, 0.35)
    out.append(dict(base, name='07_real_acarreo', duration=0.35, motor_rpm=rpm,
                    pitch_deg=round(math.degrees(math.atan(0.016)), 3),
                    description=f'Acarreo tipico: {v} km/h (mediana en movimiento), pendiente +1.6 % '
                                f'(mediana), motor {rpm_of(v):.0f} rpm. ' + note))
    v = 10.27; rpm, _ = speed_profile([], v, 0.35)
    out.append(dict(base, name='08_real_subida_cargado', duration=0.35, motor_rpm=rpm,
                    pitch_deg=round(math.degrees(math.atan(0.078)), 3),
                    description=f'Cargado en subida (carga > 100 t, pendiente > 5 %): {v} km/h y +7.8 % '
                                f'(medianas), motor {rpm_of(v):.0f} rpm. ' + note))
    v = 20.47; rpm, acc = speed_profile([(SPINUP, 0.35, -0.5)], v, 0.35)
    out.append(dict(base, name='09_real_bajada_retardo', duration=0.35, motor_rpm=rpm, accel=acc,
                    pitch_deg=round(-math.degrees(math.atan(0.06)), 3),
                    description=f'Bajada con retardo electrico: {v} km/h y -6.0 % (medianas), desaceleracion '
                                f'-0.5 m/s2 (cuartil 25 %) desde {SPINUP} s; motor {rpm_of(v):.0f} rpm. ' + note))
    return out


if __name__ == '__main__':
    main()
